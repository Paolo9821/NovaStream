/** Languages offered in Settings. [code] matches the ISO 639-1 language tag. */
enum class Language(val code: String, val nativeLabel: String) {
    ENGLISH("en", "English"),
    ITALIAN("it", "Italiano"),
    SPANISH("es", "Español"),
    FRENCH("fr", "Français"),
    GERMAN("de", "Deutsch"),
    PORTUGUESE("pt", "Português"),
    ROMANIAN("ro", "Română"),
    TURKISH("tr", "Türkçe");

    companion object {
        fun fromCode(code: String?): Language =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: ENGLISH
    }
}

